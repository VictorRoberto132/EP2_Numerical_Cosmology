def shell_modes(L, Ng, k_c, dk):
    """Integer vectors n of the mesh with |k| in [k_c - dk/2, k_c + dk/2)."""
    k_f = 2.0 * np.pi / L
    n1d = (np.fft.fftfreq(Ng) * Ng).astype(int)
    nx, ny, nz = np.meshgrid(n1d, n1d, n1d, indexing="ij")
    n = np.stack([nx, ny, nz], axis=-1).reshape(-1, 3)
    k = k_f * np.sqrt(np.sum(n**2, axis=1))
    return n[(k >= k_c - dk / 2) & (k < k_c + dk / 2)]


def triangles(L, Ng, k1, k2, k3, dk, chunk=200):
    """
    All closed lattice triangles k1 + k2 + k3 = 0 with |k_i| in shell i (width dk).

    For every pair (k1, k2) of the first two shells, k3 = -(k1 + k2) is kept if it falls in
    shell 3. Shells must stay below the Nyquist frequency, so k3 never wraps around the mesh.

    Returns a dict with the integer vectors n1, n2, n3 (each N_T x 3) and the flat mesh indices
    i1, i2, i3 used to read delta_k (numpy FFT order).
    """
    k_f = 2.0 * np.pi / L
    m1 = shell_modes(L, Ng, k1, dk)
    m2 = shell_modes(L, Ng, k2, dk)

    n1_list, n2_list, n3_list = [], [], []
    for start in range(0, len(m1), chunk):       # chunks of k1 to limit memory
        a = m1[start:start + chunk]
        n3 = -(a[:, None, :] + m2[None, :, :])   # all pairs in this chunk
        k3_mod = k_f * np.sqrt(np.sum(n3**2, axis=-1))
        ok = (k3_mod >= k3 - dk / 2) & (k3_mod < k3 + dk / 2)
        i_a, i_b = np.nonzero(ok)
        n1_list.append(a[i_a])
        n2_list.append(m2[i_b])
        n3_list.append(n3[i_a, i_b])

    n1, n2, n3 = (np.concatenate(x) for x in (n1_list, n2_list, n3_list))

    def flat(n):
        m = n % Ng
        return (m[:, 0] * Ng + m[:, 1]) * Ng + m[:, 2]

    return {"n1": n1, "n2": n2, "n3": n3, "i1": flat(n1), "i2": flat(n2), "i3": flat(n3),
            "L": L, "Ng": Ng, "k": (k1, k2, k3), "dk": dk}


def bispectrum(delta_k, tri):
    """Direct estimator (eq. C.9): B_hat = (1 / (N_T V)) sum_T Re[delta_k1 delta_k2 delta_k3]."""
    V = tri["L"]**3
    d = delta_k.reshape(-1)
    return np.mean(np.real(d[tri["i1"]] * d[tri["i2"]] * d[tri["i3"]])) / V


def btree_binned(tri, P_lin):
    """
    Tree-level bispectrum (eq. 6.15) averaged over the same lattice triangles as the estimator:
        B_tree = 2 F2(k1, k2) P(k1) P(k2) + 2 F2(k2, k3) P(k2) P(k3) + 2 F2(k3, k1) P(k3) P(k1).
    P_lin is a function of |k|.
    """
    k_f = 2.0 * np.pi / tri["L"]
    k1, k2, k3 = (k_f * tri[s] for s in ("n1", "n2", "n3"))
    P1, P2, P3 = (P_lin(np.sqrt(dot(v, v))) for v in (k1, k2, k3))
    B = (2.0 * F2_sym(k1, k2) * P1 * P2 + 2.0 * F2_sym(k2, k3) * P2 * P3
         + 2.0 * F2_sym(k3, k1) * P3 * P1)
    return np.mean(B)


