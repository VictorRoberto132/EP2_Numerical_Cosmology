def band_mask(Ng):
    """
    Modes kept in the convolution: every component |n_i| < Ng/2.
    The Nyquist planes (n_i = -Ng/2) are excluded: +Ng/2 and -Ng/2 share the same cell,
    so the direction of k (and F2) is ambiguous there.
    """
    n = np.fft.fftfreq(Ng) * Ng
    inside = np.abs(n) < Ng / 2
    return inside[:, None, None] & inside[None, :, None] & inside[None, None, :]


def embed(delta_k, M):
    """
    Copy the band-limited modes of an Ng^3 array into an M^3 array (M >= Ng) of zeros,
    at the same integer wavevector n (numpy FFT order). Inverse of `extract`.
    """
    Ng = delta_k.shape[0]
    n = (np.fft.fftfreq(Ng) * Ng).astype(int)
    keep = np.abs(n) < Ng / 2                      # drop the Nyquist index
    idx_small = np.arange(Ng)[keep]
    idx_big = n[keep] % M                          # position of the same n on the M grid
    big = np.zeros((M, M, M), dtype=complex)
    big[np.ix_(idx_big, idx_big, idx_big)] = delta_k[np.ix_(idx_small, idx_small, idx_small)]
    return big


def extract(big_k, Ng):
    """Read the modes |n_i| < Ng/2 of an M^3 array back into an Ng^3 array (Nyquist = 0)."""
    M = big_k.shape[0]
    n = (np.fft.fftfreq(Ng) * Ng).astype(int)
    keep = np.abs(n) < Ng / 2
    idx_small = np.arange(Ng)[keep]
    idx_big = n[keep] % M
    small = np.zeros((Ng, Ng, Ng), dtype=complex)
    small[np.ix_(idx_small, idx_small, idx_small)] = big_k[np.ix_(idx_big, idx_big, idx_big)]
    return small


def delta2_fft(delta_k, L, pad=True):
    """
    delta_2,k of eq. C.5 computed with FFTs.

    F2 (eq. 5.21) splits into three products of real-space fields:
        5/7                        ->  (5/7) delta^2
        (mu/2)(k1/k2 + k2/k1)      ->  - Psi . grad(delta),    Psi_k = i (k/k^2) delta_k
        (2/7) mu^2                 ->  (2/7) sum_ij T_ij T_ij,  T_ij,k = (k_i k_j / k^2) delta_k
    so delta_2(x) = (5/7) delta^2 - Psi.grad(delta) + (2/7) T_ij T_ij.

    Band limit and aliasing: the input uses only |n_i| < Ng/2. With pad=True the products are
    evaluated on a 2Ng mesh (zero padding), which holds every sum q + (k - q) without wrapping,
    so no aliasing occurs; only the output modes |n_i| < Ng/2 are kept (the true delta_2 also
    has modes up to 2 k_Ny, which the Ng mesh cannot represent). With pad=False the products
    are taken on the Ng mesh itself and modes beyond the band alias back into it.

    Zero mode: F2(q, -q) = 0, so delta_2,0 = 0 analytically; it is set to 0 explicitly.
    """
    Ng = delta_k.shape[0]
    M = 2 * Ng if pad else Ng

    # Input modes on the working mesh (Nyquist planes removed)
    dk = embed(delta_k, M)
    kx, ky, kz = ex3.wavevectors(L, M)
    kvec = [kx, ky, kz]
    k2 = kx**2 + ky**2 + kz**2
    inv_k2 = np.zeros_like(k2)
    inv_k2[k2 > 0] = 1.0 / k2[k2 > 0]

    # Local term: (5/7) delta^2
    d = ex3.field_x(dk, L)
    d2_x = 5.0 / 7.0 * d**2

    # Advection term: - Psi . grad(delta)
    for ki in kvec:
        Psi_i = ex3.field_x(1j * ki * inv_k2 * dk, L)
        grad_i = ex3.field_x(1j * ki * dk, L)
        d2_x -= Psi_i * grad_i

    # Tidal term: (2/7) sum_ij T_ij^2  (off-diagonal terms counted twice)
    for i in range(3):
        for j in range(i, 3):
            T_ij = ex3.field_x(kvec[i] * kvec[j] * inv_k2 * dk, L)
            d2_x += (2.0 / 7.0) * (1.0 if i == j else 2.0) * T_ij**2

    # Back to Fourier space, keep the Ng band, zero mode = 0
    d2_k = extract(ex3.field_k(d2_x, L), Ng)
    d2_k[0, 0, 0] = 0.0
    return d2_k


def delta2_direct(delta_k, L):
    """
    Direct evaluation of eq. C.5 on a small mesh (cost ~ Ng^6), used to test delta2_fft.
    Sum over q with q and k - q inside the band |n_i| < Ng/2 (no periodic wrapping), q != 0, k - q != 0.
    """
    Ng = delta_k.shape[0]
    V = L**3
    k_f = 2.0 * np.pi / L

    # Integer vectors of the band and their delta values
    n1d = (np.fft.fftfreq(Ng) * Ng).astype(int)
    nx, ny, nz = np.meshgrid(n1d, n1d, n1d, indexing="ij")
    n_all = np.stack([nx, ny, nz], axis=-1).reshape(-1, 3)
    d_all = delta_k.reshape(-1)
    band = np.all(np.abs(n_all) < Ng / 2, axis=1) & np.any(n_all != 0, axis=1)
    nq, dq = n_all[band], d_all[band]

    d2_k = np.zeros_like(delta_k)
    for n_out in n_all[np.all(np.abs(n_all) < Ng / 2, axis=1)]:
        if not np.any(n_out):
            continue                                 # zero mode stays 0
        n_p = n_out - nq                             # k - q for every q
        ok = np.all(np.abs(n_p) < Ng / 2, axis=1) & np.any(n_p != 0, axis=1)
        d_p = delta_k[tuple((n_p[ok] % Ng).T)]       # delta at k - q
        F2 = F2_sym(k_f * nq[ok], k_f * n_p[ok])
        d2_k[tuple(n_out % Ng)] = np.sum(F2 * dq[ok] * d_p) / V
    return d2_k


