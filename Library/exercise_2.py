# ---------------------------------------------------------------------------
# Mode-coupling kernels (eqs. 3.21-3.33, 5.21, A.9-A.11)
# Vectors are arrays with the 3 components in the last axis.
# ---------------------------------------------------------------------------

def dot(a, b):
    """Scalar product over the last axis."""
    return np.sum(a * b, axis=-1)


def safe_divide(num, den):
    """num / den, set to 0 where den = 0 (kernels with a zero input vector, see F3_sym)."""
    out = np.zeros(np.broadcast(num, den).shape)
    np.divide(num, den, out=out, where=(den != 0))
    return out


def alpha(k1, k2):
    """Continuity kernel alpha(k1, k2) = (k1 + k2).k1 / k1^2 (notes Section 3.4)."""
    return safe_divide(dot(k1 + k2, k1), dot(k1, k1))


def beta(k1, k2):
    """Euler kernel beta(k1, k2) = |k1 + k2|^2 (k1.k2) / (2 k1^2 k2^2) (notes Section 3.5)."""
    k12 = k1 + k2
    return safe_divide(dot(k12, k12) * dot(k1, k2), 2.0 * dot(k1, k1) * dot(k2, k2))


def F2_sym(k1, k2):
    """
    Symmetric EdS kernel (eq. 5.21):
        F2 = 5/7 + (mu/2)(k1/k2 + k2/k1) + (2/7) mu^2,   mu = k1_hat . k2_hat.
    """
    m1 = np.sqrt(dot(k1, k1))
    m2 = np.sqrt(dot(k2, k2))
    mu = dot(k1, k2) / (m1 * m2)
    return 5.0 / 7.0 + 0.5 * mu * (m1 / m2 + m2 / m1) + 2.0 / 7.0 * mu**2


def F2_unsym(q1, q2):
    """Unsymmetrized F2 = (5 alpha + 2 beta) / 7 (eq. A.11)."""
    return (5.0 * alpha(q1, q2) + 2.0 * beta(q1, q2)) / 7.0


def G2_unsym(q1, q2):
    """Unsymmetrized G2 = (3 alpha + 4 beta) / 7 (eq. A.11)."""
    return (3.0 * alpha(q1, q2) + 4.0 * beta(q1, q2)) / 7.0


def F3_unsym(q1, q2, q3):
    """
    Unsymmetrized F3 from the EdS recursion (eq. A.9) with n = 3, d_3 = 18, 2n + 1 = 7:
        m = 1:  G1(q1)     [7 alpha(q1, q2+q3) F2(q2, q3) + 2 beta(q1, q2+q3) G2(q2, q3)] / 18
        m = 2:  G2(q1, q2) [7 alpha(q1+q2, q3) F1(q3)     + 2 beta(q1+q2, q3) G1(q3)    ] / 18
    with F1 = G1 = 1.
    """
    q23 = q2 + q3
    q12 = q1 + q2
    term1 = 7.0 * alpha(q1, q23) * F2_unsym(q2, q3) + 2.0 * beta(q1, q23) * G2_unsym(q2, q3)
    term2 = G2_unsym(q1, q2) * (7.0 * alpha(q12, q3) + 2.0 * beta(q12, q3))
    return (term1 + term2) / 18.0


def F3_sym(q1, q2, q3):
    """
    Symmetric F3: average of F3_unsym over the 6 permutations of its arguments.

    For F3(k, q, -q) some permutations contain a zero vector (q + (-q) = 0), where alpha or
    beta are 0/0. Those terms multiply a G2 that vanishes linearly, and the finite leftovers of
    the two orderings (q, -q) and (-q, q) are equal and opposite, so they cancel in the
    symmetrized kernel. safe_divide sets them to 0, which gives the same sum.
    """
    perms = [(q1, q2, q3), (q1, q3, q2), (q2, q1, q3),
             (q2, q3, q1), (q3, q1, q2), (q3, q2, q1)]
    return sum(F3_unsym(*p) for p in perms) / 6.0


