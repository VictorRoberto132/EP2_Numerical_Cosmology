def _radial_grid(k, kmin, kmax, nr):
    """Logarithmic grid in r = q/k between kmin/k and kmax/k (notes 7.5, item 1)."""
    return np.logspace(np.log10(kmin / k), np.log10(kmax / k), nr)


def P22(k, P_lin, kmin, kmax, nr=2000, nnu=64, symmetric=True):
    """
    P22(k) of eq. 7.17 with q in [kmin, kmax].

    The integrand is symmetric under q <-> k - q, so we integrate only over |q| < |k - q|
    (i.e. nu < 1/(2r)) and multiply by 2. Then the region p = |k - q| -> 0 becomes the region
    q -> 0, which is controlled by the infrared cutoff kmin (notes 7.5, item 2).
        P22 = 2 * k^3/(2 pi^2) int r^2 dr int_{-1}^{min(1, 1/2r)} dnu F2^2 P(kr) P(k sqrt(1 + r^2 - 2 r nu))
    The r integral is done in ln r (trapezoid), the nu integral with Gauss-Legendre nodes.

    symmetric=False integrates naively over the full range nu in [-1, 1] (factor 1 instead of 2):
    then nothing controls p -> 0, where P(p) and F2 blow up (used only as a test).
    """
    r = _radial_grid(k, kmin, kmax, nr)
    x, w = np.polynomial.legendre.leggauss(nnu)

    # Map the Gauss-Legendre nodes from [-1, 1] to [-1, nu_max(r)]
    if symmetric:
        nu_max = np.minimum(1.0, 1.0 / (2.0 * r))[:, None]
    else:
        nu_max = np.ones_like(r)[:, None]
    nu = -1.0 + (x[None, :] + 1.0) * (nu_max + 1.0) / 2.0
    w_nu = w[None, :] * (nu_max + 1.0) / 2.0

    # q along a direction at angle nu from k = (0, 0, k); p = k - q
    kvec = np.array([0.0, 0.0, k])
    q = k * r[:, None]
    qvec = np.stack([q * np.sqrt(1.0 - nu**2), np.zeros_like(nu), q * nu], axis=-1)
    pvec = kvec - qvec
    p = np.sqrt(dot(pvec, pvec))

    integrand = F2_sym(qvec, pvec)**2 * P_lin(q) * P_lin(p)
    inner = np.sum(w_nu * integrand, axis=1)                  # nu integral
    outer = trapezoid(r**3 * inner, np.log(r))             # int r^2 dr = int r^3 d ln r
    factor = 2.0 if symmetric else 1.0                         # q < p region counted twice
    return factor * k**3 / (2.0 * np.pi**2) * outer


def P13(k, P_lin, kmin, kmax, nr=2000, nnu=64):
    """
    P13(k) of eq. 7.18 (one cross-correlation <delta_1 delta_3>), with q in [kmin, kmax]:
        P13 = 3 k^3 P(k) / (4 pi^2) int r^2 dr int_{-1}^{1} dnu F3(k, q, -q) P(kr).
    """
    r = _radial_grid(k, kmin, kmax, nr)
    nu, w = np.polynomial.legendre.leggauss(nnu)
    nu = nu[None, :]

    q = k * r[:, None]
    qvec = np.stack([q * np.sqrt(1.0 - nu**2), np.zeros_like(q * nu), q * nu], axis=-1)
    kvec = np.broadcast_to(np.array([0.0, 0.0, k]), qvec.shape)

    integrand = F3_sym(kvec, qvec, -qvec) * P_lin(q)
    inner = np.sum(w[None, :] * integrand, axis=1)
    outer = trapezoid(r**3 * inner, np.log(r))
    return 3.0 * k**3 * P_lin(k) / (4.0 * np.pi**2) * outer
